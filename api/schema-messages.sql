-- ============================================================
-- CareTask demo API — messages (staff messaging + patient chart
-- messages), Phase 1 of the messaging scope (2026-10-30), modeled
-- on OpenEMR's Messages center + patient-attached chart messages.
-- Apply AFTER schema.sql, schema-events.sql,
-- schema-patients-v2.sql and schema-users.sql:
--   psql -d caretask_demo -f schema-messages.sql
-- as the database OWNER (live tables are owned by postgres; the
-- runtime user patient_api gets grants only).
--
-- Two kinds of message in one table:
--   - direct:   recipient_id set (staff → staff), read_at tracks
--               the read receipt
--   - chart:    patient_id set (the OpenEMR chart-message
--               pattern) — visible to the whole care team on the
--               patient's profile; recipient optional (a direct
--               message can ALSO be attached to a patient).
-- CHECK enforces at least one of the two.
--
-- Threading: thread_id groups a conversation; a root message's
-- thread_id is its own id (set by the route in the same tx).
--
-- Also widens the event_log event CHECK with the two messaging
-- server events: message_send, message_read. Message BODIES are
-- never written to event_log — ids and parties only.
-- ============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS messages (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id    BIGINT,
  sender_id    BIGINT NOT NULL REFERENCES users(id),
  recipient_id BIGINT REFERENCES users(id),
  patient_id   UUID REFERENCES patients(id),
  subject      TEXT,
  body         TEXT NOT NULL,
  read_at      TIMESTAMPTZ,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at   TIMESTAMPTZ,
  CONSTRAINT messages_target_present
    CHECK (recipient_id IS NOT NULL OR patient_id IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS messages_recipient_idx
  ON messages (recipient_id, created_at DESC);
CREATE INDEX IF NOT EXISTS messages_patient_idx
  ON messages (patient_id, created_at);
CREATE INDEX IF NOT EXISTS messages_thread_idx
  ON messages (thread_id, created_at);

ALTER TABLE event_log DROP CONSTRAINT IF EXISTS event_log_event_check;
ALTER TABLE event_log ADD CONSTRAINT event_log_event_check CHECK (
  event IN (
    'patient_view', 'sign_in', 'sign_out', 'report_export',
    'auth_failure', 'admin_action', 'api_request',
    'appointment_change', 'message_send', 'message_read'
  )
);

GRANT SELECT, INSERT, UPDATE ON messages TO patient_api;
GRANT USAGE, SELECT ON SEQUENCE messages_id_seq TO patient_api;

COMMIT;
