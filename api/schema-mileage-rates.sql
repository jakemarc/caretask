-- ============================================================
-- CareTask — deploy-41 mileage rate table (Concur-style
-- upgrade, step 3 of 5): dated mileage rates. Each row covers
-- [effective_from, effective_to]; effective_to is maintained
-- by the API on insert (day before the next row's
-- effective_from, NULL for the latest). Superseding is by
-- DATE — one row per effective_from (enforced in the API).
-- Per-leg rate_per_mile snapshots on mileage_entries are
-- unchanged; this table is the reference schedule.
--
-- Apply as the database OWNER, AFTER
-- schema-expense-receipts.sql and BEFORE
-- schema-expense-policy.sql (deploy-41 order: itemization,
-- receipts, rates, policy, approvals):
--   sudo -u postgres psql -d caretask_demo -f schema-mileage-rates.sql
-- Idempotent (IF NOT EXISTS throughout).
-- ============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS mileage_rates (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rate           NUMERIC(6, 4) NOT NULL CHECK (rate >= 0),
  effective_from DATE NOT NULL,
  effective_to   DATE,
  created_by     BIGINT REFERENCES users(id),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS mileage_rates_effective_from_idx
  ON mileage_rates (effective_from DESC);

GRANT SELECT, INSERT, UPDATE ON mileage_rates TO patient_api;
GRANT USAGE, SELECT ON SEQUENCE mileage_rates_id_seq TO patient_api;

COMMIT;
