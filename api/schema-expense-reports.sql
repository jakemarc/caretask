-- ============================================================
-- CareTask demo API — expense reports + mileage entries
-- (2026-11-01, Jake's spec): mileage lives inside ONE expense
-- report per period (usually a whole month). The clinician
-- adds mileage during the month for drives between patient
-- homes; the home↔home-office commute is deducted per day
-- (daily reimbursable = total driven that day − commute,
-- never below zero). The report stays draft/editable until
-- complete, then the owner submits it for payment. Reports
-- can be printed and previous reports viewed.
--
-- Tables:
-- - expense_reports: the envelope. One report per clinician
--   (user_id → users, BY ID) per period; optional agency tag.
--   Status lifecycle draft → submitted → approved / rejected
--   → paid lives HERE (submission, approval, and payment are
--   properties of the whole report, not of single lines).
--   Title is a friendly name ("October mileage – CenterWell");
--   NULL means the UI generates one from period + agency.
-- - mileage_entries: the individual drives inside a report.
--   entry_kind 'business' = a driven leg; 'commute' = the
--   day's home↔home-office deduction leg (its miles subtract
--   instead of adding). Both routing figures are stored
--   (miles_toll / miles_no_toll) plus used_tollway, so the
--   report shows its work; business_miles is the leg's FINAL
--   miles (the chosen route's figure, ×2 when round_trip,
--   and user-correctable before saving). rate_per_mile is a
--   per-entry snapshot (rates change over time); NULL = no
--   dollar figure claimed for that leg yet.
--
-- Non-mileage lines (parking, tolls, supplies…) live in the
-- expenses table, which gains its report link in
-- schema-expenses.sql — apply THIS file BEFORE it.
--
-- Apply as the database OWNER (live tables are owned by
-- postgres; the runtime user patient_api gets grants only,
-- no DELETE — deletes are soft via deleted_at):
--   sudo -u postgres psql -d caretask_demo -f schema-expense-reports.sql
-- Idempotent (IF NOT EXISTS throughout).
-- ============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS expense_reports (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT NOT NULL REFERENCES users(id),
  agency_id    BIGINT REFERENCES agencies(id),
  title        TEXT,
  period_start DATE NOT NULL,
  period_end   DATE NOT NULL CHECK (period_end >= period_start),
  status       TEXT NOT NULL DEFAULT 'draft'
               CHECK (status IN ('draft', 'submitted', 'approved',
                                 'rejected', 'paid')),
  submitted_at TIMESTAMPTZ,
  approved_by  BIGINT REFERENCES users(id),
  approved_at  TIMESTAMPTZ,
  paid_at      TIMESTAMPTZ,
  payment_ref  TEXT,
  notes        TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at   TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS expense_reports_user_idx
  ON expense_reports (user_id, period_start DESC);
CREATE INDEX IF NOT EXISTS expense_reports_status_idx
  ON expense_reports (status, period_start DESC);

CREATE TABLE IF NOT EXISTS mileage_entries (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expense_report_id BIGINT NOT NULL REFERENCES expense_reports(id),
  entry_date        DATE NOT NULL,
  seq               INTEGER NOT NULL DEFAULT 0,
  entry_kind        TEXT NOT NULL DEFAULT 'business'
                    CHECK (entry_kind IN ('business', 'commute')),
  start_address     TEXT,
  end_address       TEXT,
  start_lat         DOUBLE PRECISION,
  start_lng         DOUBLE PRECISION,
  end_lat           DOUBLE PRECISION,
  end_lng           DOUBLE PRECISION,
  appointment_id    BIGINT REFERENCES appointments(id),
  miles_toll        NUMERIC(7, 2),
  miles_no_toll     NUMERIC(7, 2),
  used_tollway      BOOLEAN NOT NULL DEFAULT false,
  round_trip        BOOLEAN NOT NULL DEFAULT false,
  business_miles    NUMERIC(7, 2) NOT NULL CHECK (business_miles >= 0),
  rate_per_mile     NUMERIC(6, 4) CHECK (rate_per_mile IS NULL OR rate_per_mile >= 0),
  vehicle           TEXT,
  notes             TEXT,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at        TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS mileage_entries_report_idx
  ON mileage_entries (expense_report_id, entry_date, seq);

CREATE OR REPLACE FUNCTION expense_reports_set_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS expense_reports_updated_at ON expense_reports;
CREATE TRIGGER expense_reports_updated_at
  BEFORE UPDATE ON expense_reports
  FOR EACH ROW EXECUTE FUNCTION expense_reports_set_updated_at();

CREATE OR REPLACE FUNCTION mileage_entries_set_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS mileage_entries_updated_at ON mileage_entries;
CREATE TRIGGER mileage_entries_updated_at
  BEFORE UPDATE ON mileage_entries
  FOR EACH ROW EXECUTE FUNCTION mileage_entries_set_updated_at();

GRANT SELECT, INSERT, UPDATE ON expense_reports TO patient_api;
GRANT USAGE, SELECT ON SEQUENCE expense_reports_id_seq TO patient_api;
GRANT SELECT, INSERT, UPDATE ON mileage_entries TO patient_api;
GRANT USAGE, SELECT ON SEQUENCE mileage_entries_id_seq TO patient_api;

COMMIT;
