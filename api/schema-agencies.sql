-- ============================================================
-- CareTask demo API — agencies (home-health agency directory),
-- v1 (2026-10-30). Source of record is NOT CareTask: the rows
-- are imported from the IDPH Home Health Agency Directory
-- (Illinois open data, Socrata dataset p7mg-cnpx on
-- illinois-edp.data.socrata.com — see
-- ../agency-directory-research.md). Source fields are refreshed
-- by the sync (lib/agencySync.js); three LOCAL fields are never
-- touched by a sync:
--   is_primary — the agency this CareTask instance belongs to
--     ("our agency"). At most one row: enforced by the partial
--     unique index below, not just by the route.
--   notes — free-text local notes.
--   short_name — a local short display name (manager-PIN
--     editable). Display precedence for the dashboard's
--     display_name (computed in routes/agencies.js):
--       1. short_name (this column)
--       2. the DBA embedded in the IDPH facility name
--          (parsed at import into dba)
--       3. the first two words of the agency name
--       4. the full name (when it is ≤ 2 words)
--
-- BIGINT identity id (like users / appointments / documents —
-- this is a directory table, not a clinical record; patients'
-- UUIDs exist because patient ids travel in URLs and events).
--
-- Deactivation, never deletion: a sync marks agencies that are
-- absent from the latest IDPH snapshot active = false. Rows are
-- never hard-deleted by the sync or the API (no DELETE grant).
--
-- Apply AFTER schema.sql, schema-events.sql,
-- schema-patients-v2.sql, schema-patients-map.sql,
-- schema-users.sql, schema-appointments.sql,
-- schema-messages.sql and schema-documents.sql:
--   psql -d caretask_demo -f schema-agencies.sql
-- as the database OWNER (live tables are owned by postgres; the
-- runtime user patient_api gets grants only).
--
-- Also widens the event_log event CHECK with the new server
-- event agency_sync. Sync event details are COUNTS ONLY
-- (fetched / inserted / updated / deactivated / skipped) plus
-- the source rowsUpdatedAt stamp — never agency row content.
-- ============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS agencies (
  id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Natural key from IDPH; the sync upserts on it.
  license_number           TEXT NOT NULL UNIQUE,
  -- Source fields (owned by IDPH; refreshed by every sync).
  name                     TEXT NOT NULL,
  dba                      TEXT,
  street                   TEXT,
  city                     TEXT,
  state                    TEXT NOT NULL DEFAULT 'IL',
  postal_code              TEXT,
  county                   TEXT,
  phone                    TEXT,
  admin_contact_name       TEXT,
  license_expiration_date  DATE,
  source                   TEXT NOT NULL DEFAULT 'idph',
  -- rowsUpdatedAt of the IDPH snapshot this row came from.
  source_updated_at        TIMESTAMPTZ,
  last_synced_at           TIMESTAMPTZ,
  active                   BOOLEAN NOT NULL DEFAULT true,
  -- Local-only fields (sync NEVER overwrites these).
  is_primary               BOOLEAN NOT NULL DEFAULT false,
  notes                    TEXT,
  short_name               TEXT,
  created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at               TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS agencies_name_idx ON agencies (name);
CREATE INDEX IF NOT EXISTS agencies_city_idx ON agencies (city);

-- At most one "our agency" row, enforced by the database.
CREATE UNIQUE INDEX IF NOT EXISTS agencies_one_primary_idx
  ON agencies (is_primary) WHERE is_primary = true;

CREATE OR REPLACE FUNCTION agencies_set_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS agencies_updated_at ON agencies;
CREATE TRIGGER agencies_updated_at
  BEFORE UPDATE ON agencies
  FOR EACH ROW EXECUTE FUNCTION agencies_set_updated_at();

ALTER TABLE event_log DROP CONSTRAINT IF EXISTS event_log_event_check;
ALTER TABLE event_log ADD CONSTRAINT event_log_event_check CHECK (
  event IN (
    'patient_view', 'sign_in', 'sign_out', 'report_export',
    'auth_failure', 'admin_action', 'api_request',
    'appointment_change', 'message_send', 'message_read',
    'document_create', 'document_update', 'document_finalize',
    'agency_sync'
  )
);

GRANT SELECT, INSERT, UPDATE ON agencies TO patient_api;
GRANT USAGE, SELECT ON SEQUENCE agencies_id_seq TO patient_api;

COMMIT;
