-- ============================================================
-- CareTask demo API — documents (clinical documentation),
-- v1 (2026-10-30), modeled on OpenEMR's encounter forms:
-- a document is tied to a patient (optionally to an
-- appointment), authored by a staff user, and holds its
-- content as sections JSONB whose keys come from the
-- template for its doc_type (see lib/documentTemplates.js:
-- evaluation / reassessment / discharge).
--
-- Apply AFTER schema.sql, schema-events.sql,
-- schema-patients-v2.sql, schema-users.sql,
-- schema-appointments.sql and schema-messages.sql:
--   psql -d caretask_demo -f schema-documents.sql
-- as the database OWNER (live tables are owned by postgres; the
-- runtime user patient_api gets grants only).
--
-- Lifecycle: status 'draft' → 'finalized'. A finalized document
-- is locked (the route rejects edits with 409 DOCUMENT_FINALIZED,
-- the OpenEMR e-sign pattern); finalized_at / finalized_by record
-- who signed it off and when. Deletes are soft (deleted_at),
-- like patients, appointments and messages.
--
-- Also widens the event_log event CHECK with the three document
-- server events: document_create, document_update,
-- document_finalize. Section CONTENT and document titles are
-- never written to event_log — ids and doc_type only.
-- ============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS documents (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id   UUID NOT NULL REFERENCES patients(id),
  appointment_id BIGINT REFERENCES appointments(id),
  author_id    BIGINT NOT NULL REFERENCES users(id),
  doc_type     TEXT NOT NULL
               CHECK (doc_type IN ('evaluation', 'reassessment', 'discharge')),
  title        TEXT,
  sections     JSONB NOT NULL DEFAULT '{}'::jsonb,
  status       TEXT NOT NULL DEFAULT 'draft'
               CHECK (status IN ('draft', 'finalized')),
  finalized_at TIMESTAMPTZ,
  finalized_by BIGINT REFERENCES users(id),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at   TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS documents_patient_idx
  ON documents (patient_id, created_at DESC);
CREATE INDEX IF NOT EXISTS documents_author_idx
  ON documents (author_id);

CREATE OR REPLACE FUNCTION documents_set_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS documents_updated_at ON documents;
CREATE TRIGGER documents_updated_at
  BEFORE UPDATE ON documents
  FOR EACH ROW EXECUTE FUNCTION documents_set_updated_at();

ALTER TABLE event_log DROP CONSTRAINT IF EXISTS event_log_event_check;
ALTER TABLE event_log ADD CONSTRAINT event_log_event_check CHECK (
  event IN (
    'patient_view', 'sign_in', 'sign_out', 'report_export',
    'auth_failure', 'admin_action', 'api_request',
    'appointment_change', 'message_send', 'message_read',
    'document_create', 'document_update', 'document_finalize'
  )
);

GRANT SELECT, INSERT, UPDATE ON documents TO patient_api;
GRANT USAGE, SELECT ON SEQUENCE documents_id_seq TO patient_api;

COMMIT;
