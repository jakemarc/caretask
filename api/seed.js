async function main() {
  // CASCADE: appointments references patients (FK) — a demo reseed
  // clears appointments along with the patients they point at.
  await pool.query('TRUNCATE audit_log, patients CASCADE');
  for (const p of PATIENTS) {
    const placeholders = COLUMNS.map((_, i) => `$${i + 1}`).join(', ');
    await pool.query(
      `INSERT INTO patients (${COLUMNS.join(', ')}) VALUES (${placeholders})`,
      COLUMNS.map((c) => p[c] ?? null),
    );
  }
  console.log(`Seeded ${PATIENTS.length} fictional demo patients.`);
  await pool.end();
}

main().catch(async (err) => {
  console.error('seed failed:', err.message);
  await pool.end();
  process.exit(1);
});
