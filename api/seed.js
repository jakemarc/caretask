// them), and TRUNCATE does not fire row triggers. This is a
// setup-time reset by the table owner, not something the API does:
// the API never issues TRUNCATE, and its role in production should
// not own the tables. event_log is intentionally NOT truncated:
// its patient_id is informational (no foreign key), so old event
// rows stay readable after a reset. Never run this against tables
// holding real data. Run it with: npm run seed (after schema.sql,
// schema-events.sql, and schema-patients-v2.sql have been applied).
// Seed rows have no audit entries by design: the audit trail records
// API mutations by a signed-in user, and seeding is setup, not a
