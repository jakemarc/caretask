-- ============================================================
-- CareTask — deploy-41 expense approvals (Concur-style
-- upgrade, step 5 of 5): restores the report lifecycle for
-- NEW chain-model reports while legacy envelopes stay
-- readable with their original math.
--
-- - expense_reports.model: 'legacy' for pre-deploy-41
--   envelopes (default, so existing rows are legacy),
--   'chain' for reports created by deploy-41 (built from
--   linked day-log legs + expense lines).
-- - expense_report_events: the approval timeline — one row
--   per status transition (including creation), oldest first
--   in reads. Self-approval is blocked in the API.
--
-- Apply as the database OWNER, AFTER
-- schema-expense-policy.sql (deploy-41 order: itemization,
-- receipts, rates, policy, approvals):
--   sudo -u postgres psql -d caretask_demo -f schema-expense-approvals.sql
-- Idempotent (IF NOT EXISTS throughout).
-- ============================================================

BEGIN;

ALTER TABLE expense_reports
  ADD COLUMN IF NOT EXISTS model TEXT NOT NULL DEFAULT 'legacy'
  CHECK (model IN ('legacy', 'chain'));

CREATE TABLE IF NOT EXISTS expense_report_events (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id   BIGINT NOT NULL REFERENCES expense_reports(id),
  actor_id    BIGINT NOT NULL REFERENCES users(id),
  from_status TEXT,
  to_status   TEXT NOT NULL,
  note        TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS expense_report_events_report_idx
  ON expense_report_events (report_id, created_at);

GRANT SELECT, INSERT, UPDATE ON expense_reports TO patient_api;
GRANT USAGE, SELECT ON SEQUENCE expense_reports_id_seq TO patient_api;
GRANT SELECT, INSERT, UPDATE ON expense_report_events TO patient_api;
GRANT USAGE, SELECT ON SEQUENCE expense_report_events_id_seq TO patient_api;

COMMIT;
