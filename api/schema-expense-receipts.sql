-- ============================================================
-- CareTask — deploy-41 expense receipts (Concur-style
-- upgrade, step 2 of 5): receipt files stored in Postgres
-- (BYTEA) attached to exactly one parent line — a mileage
-- leg OR a non-mileage expense line.
--
-- The legacy expenses.receipt_url column is dead and left
-- alone; this table supersedes it. File bytes never go to
-- the event log. Deletes are soft via deleted_at.
--
-- Apply as the database OWNER, AFTER
-- schema-expense-itemization.sql and BEFORE
-- schema-mileage-rates.sql (deploy-41 order: itemization,
-- receipts, rates, policy, approvals):
--   sudo -u postgres psql -d caretask_demo -f schema-expense-receipts.sql
-- Idempotent (IF NOT EXISTS throughout).
-- ============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS expense_receipts (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mileage_entry_id BIGINT REFERENCES mileage_entries(id),
  expense_id       BIGINT REFERENCES expenses(id),
  user_id          BIGINT NOT NULL REFERENCES users(id),
  filename         TEXT,
  mime_type        TEXT NOT NULL,
  size_bytes       INTEGER NOT NULL CHECK (size_bytes >= 0),
  data             BYTEA NOT NULL,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at       TIMESTAMPTZ,
  CONSTRAINT expense_receipts_exactly_one_parent CHECK (
    (mileage_entry_id IS NOT NULL AND expense_id IS NULL)
    OR (mileage_entry_id IS NULL AND expense_id IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS expense_receipts_mileage_idx
  ON expense_receipts (mileage_entry_id);
CREATE INDEX IF NOT EXISTS expense_receipts_expense_idx
  ON expense_receipts (expense_id);

GRANT SELECT, INSERT, UPDATE ON expense_receipts TO patient_api;
GRANT USAGE, SELECT ON SEQUENCE expense_receipts_id_seq TO patient_api;

COMMIT;
