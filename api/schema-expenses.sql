-- ============================================================
-- CareTask demo API — expenses (staff expense records), v1
-- (2026-10-31). One row per expense a staff member incurred:
-- mileage, parking, tolls, supplies, meals and the rest of the
-- standard category list.
--
-- THE USERS CONNECTION: an expense belongs to a staff member
-- through user_id → users(id), deliberately NOT through a name
-- string. Names are not unique (two staff can share a name)
-- and they change; the id never does. The name shown on screen
-- is read from the users table with a JOIN at query time, e.g.:
--
--   SELECT e.*, u.lname || ', ' || u.fname AS employee_name
--   FROM expenses e
--   JOIN users u ON u.id = e.user_id
--   ORDER BY e.expense_date DESC;
--
-- approved_by is a second users link (the manager who approved).
-- agency_id optionally ties the expense to an agency.
--
-- Category is a CHECK list for v1 (the twelve standard
-- categories Jake approved 2026-10-31). If categories ever need
-- to be edited from the UI, this column becomes a FK to an
-- expense_categories table — the values carry over as-is.
--
-- Amounts are stored as integer cents (amount_cents) so money
-- never goes through floating point. Mileage trips keep their
-- own detail (from/to, miles, rate) in a separate
-- mileage_entries table that links back to the expense row —
-- NOT in this table; a mileage expense here carries only the
-- computed total in amount_cents.
--
-- Apply AFTER schema.sql, schema-events.sql,
-- schema-patients-v2.sql, schema-users.sql and
-- schema-agencies.sql (i.e. last, after every existing schema):
--   psql -d caretask_demo -f schema-expenses.sql
-- as the database OWNER (live tables are owned by postgres; the
-- runtime user patient_api gets grants only, no DELETE —
-- deletes are soft via deleted_at, like patients).
--
-- Lifecycle: status 'draft' → 'submitted' → 'approved' /
-- 'rejected' → 'reimbursed'. submitted_at / approved_at /
-- reimbursed_at stamp each step; approved_by records who
-- approved. Also widens the event_log event CHECK with
-- 'expense_change' (additive only — expense ids and status
-- changes may be logged; amounts and notes never are).
-- ============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS expenses (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id           BIGINT NOT NULL REFERENCES users(id),
  expense_date      DATE NOT NULL,
  category          TEXT NOT NULL
                    CHECK (category IN ('mileage', 'parking', 'tolls',
                                        'medical_supplies', 'office_supplies',
                                        'meals', 'travel', 'lodging',
                                        'phone_internet', 'training',
                                        'licenses', 'other')),
  description       TEXT,
  vendor_name       TEXT,
  amount_cents      INTEGER NOT NULL CHECK (amount_cents >= 0),
  currency          TEXT NOT NULL DEFAULT 'USD',
  payment_method    TEXT
                    CHECK (payment_method IN ('personal_card', 'company_card',
                                              'cash', 'other')),
  receipt_url       TEXT,
  agency_id         BIGINT REFERENCES agencies(id),
  status            TEXT NOT NULL DEFAULT 'draft'
                    CHECK (status IN ('draft', 'submitted', 'approved',
                                      'rejected', 'reimbursed')),
  submitted_at      TIMESTAMPTZ,
  approved_by       BIGINT REFERENCES users(id),
  approved_at       TIMESTAMPTZ,
  reimbursed_at     TIMESTAMPTZ,
  reimbursement_ref TEXT,
  notes             TEXT,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at        TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS expenses_user_idx
  ON expenses (user_id, expense_date DESC);
CREATE INDEX IF NOT EXISTS expenses_status_idx
  ON expenses (status, expense_date DESC);

CREATE OR REPLACE FUNCTION expenses_set_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS expenses_updated_at ON expenses;
CREATE TRIGGER expenses_updated_at
  BEFORE UPDATE ON expenses
  FOR EACH ROW EXECUTE FUNCTION expenses_set_updated_at();

ALTER TABLE event_log DROP CONSTRAINT IF EXISTS event_log_event_check;
ALTER TABLE event_log ADD CONSTRAINT event_log_event_check CHECK (
  event IN (
    'patient_view', 'sign_in', 'sign_out', 'report_export',
    'auth_failure', 'admin_action', 'api_request',
    'appointment_change', 'message_send', 'message_read',
    'document_create', 'document_update', 'document_finalize',
    'agency_sync', 'expense_change'
  )
);

GRANT SELECT, INSERT, UPDATE ON expenses TO patient_api;
GRANT USAGE, SELECT ON SEQUENCE expenses_id_seq TO patient_api;

COMMIT;
