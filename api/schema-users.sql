-- CareTask demo API — users table (staff / clinician directory).
--
-- Modeled on OpenEMR's `users` table (core fields only, Jake's call
-- 2026-10-29), plus two CareTask additions:
--   firebase_uid — links the row to the Firebase Auth account that
--     actually signs in. Logins/passwords stay in Firebase; this table
--     NEVER stores a password.
--   role — OpenEMR keeps roles in separate ACL tables; one column is
--     the leaner version. `authorized` stays a separate flag: it means
--     "can be assigned patients" (providers only), which is a different
--     question from "what is their job" (role) — a developer or DBA is
--     a user with a role but authorized = false.
--   pin_hash — the manager override PIN, stored ONLY as a scrypt hash
--     (see lib/pin.js). Set only for manager/admin rows. The API checks
--     it server-side on patient update/delete/restore; the dashboard
--     never sees or stores it. NULL = no PIN set for that user.
--
-- Apply AFTER schema.sql, schema-events.sql, schema-patients-v2.sql,
-- as the table OWNER (live tables are owned by postgres; the runtime
-- API user cannot CREATE):
--   sudo -u postgres psql -d caretask_demo -f schema-users.sql
-- Then grant the runtime user (name differs per environment):
--   GRANT SELECT, INSERT, UPDATE ON users TO patient_api;
--   GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO patient_api;
-- (No DELETE grant: staff are deactivated with active = false, never
-- removed — same soft-delete philosophy as patients.)

CREATE TABLE IF NOT EXISTS users (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  firebase_uid          TEXT UNIQUE,
  email                 TEXT NOT NULL UNIQUE CHECK (email = lower(email)),
  role                  TEXT NOT NULL DEFAULT 'clinician'
                          CHECK (role IN ('clinician', 'manager', 'admin',
                                          'developer', 'support', 'billing',
                                          'front_office')),
  authorized            BOOLEAN NOT NULL DEFAULT false,
  active                BOOLEAN NOT NULL DEFAULT true,
  -- Name.
  fname                 TEXT NOT NULL,
  mname                 TEXT,
  lname                 TEXT NOT NULL,
  suffix                TEXT,
  title                 TEXT,
  valedictory           TEXT,
  -- Provider credentials.
  npi                   TEXT,
  taxonomy              TEXT,
  specialty             TEXT,
  physician_type        TEXT,
  state_license_number  TEXT,
  federaldrugid         TEXT,
  federaltaxid          TEXT,
  -- Affiliation (facility_id is a plain number for now — no facility
  -- table exists yet, so deliberately no FK).
  facility              TEXT,
  facility_id           INTEGER,
  organization          TEXT,
  -- Contact (one address block; OpenEMR carries two — dropped as cruft).
  street                TEXT,
  city                  TEXT,
  state                 TEXT,
  zip                   TEXT,
  phone                 TEXT,
  phonecell             TEXT,
  fax                   TEXT,
  -- Notes.
  info                  TEXT,
  notes                 TEXT,
  -- Manager override PIN, scrypt hash only (lib/pin.js format).
  pin_hash              TEXT,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS users_email_lower_idx ON users (lower(email));

-- Keep updated_at honest on every UPDATE (same pattern as patients).
CREATE OR REPLACE FUNCTION users_set_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS users_updated_at ON users;
CREATE TRIGGER users_updated_at
  BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION users_set_updated_at();
